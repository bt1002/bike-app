#!/usr/bin/env python3
"""Generates the MerachRide logo: Android vector drawables for both apps, plus branding/logo.svg.

The design: a resistance dial (a 270° gauge, filled teal → amber → orange up to a white knob) around
the app's workout profile (two steps, then a ramp). Everything is drawn on the 108 × 108 dp adaptive
icon canvas; launchers show the middle 72 dp and may mask it to a circle, so the art stays within
r = 33 of the centre.

Run from the repo root:  python3 tools/icon/make_icon.py
"""
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

BG_TOP, BG_BOTTOM = "#16294A", "#0A1222"
WARM = [(0.0, "#2EC4B6"), (0.55, "#FFB703"), (1.0, "#FB5607")]
C, R, STROKE = 54.0, 26.0, 6.0
START, FILL_END, TRACK_END = 135.0, 335.0, 405.0  # Degrees, clockwise from 3 o'clock.
KNOB_R = 5.0
PROFILE = "M38,67 V59.5 H45.5 V54 H53 L62.5,44.5 H70 V67 Z"
PROFILE_STROKE = 1.5  # Same colour as the fill, with round joins, to soften the corners.


def pt(a, r=R):
    return C + r * math.cos(math.radians(a)), C + r * math.sin(math.radians(a))


def arc(a0, a1, r=R):
    x0, y0 = pt(a0, r)
    x1, y1 = pt(a1, r)
    large = 1 if (a1 - a0) > 180 else 0
    return f"M{x0:.3f},{y0:.3f} A{r:g},{r:g} 0 {large},1 {x1:.3f},{y1:.3f}"


def circle(cx, cy, r):
    return f"M{cx - r:.3f},{cy:.3f} a{r:g},{r:g} 0 1,0 {2 * r:g},0 a{r:g},{r:g} 0 1,0 {-2 * r:g},0 Z"


KNOB = circle(*pt(FILL_END), KNOB_R)
# Gradient line for the dial: bottom-left to top-right of the gauge.
G0, G1 = (C - R - 3, C + R + 3), (C + R + 3, C - R - 3)


def argb(hex_rgb, alpha="FF"):
    return "#" + alpha + hex_rgb.lstrip("#")


# ------------------------------------------------------------------ Android vectors

VEC_HEAD = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tools/icon/make_icon.py. Edit that, not this. -->\n"
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    xmlns:aapt="http://schemas.android.com/aapt"\n'
    '    android:width="108dp"\n    android:height="108dp"\n'
    '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
)


def gradient(x0, y0, x1, y1, stops, indent="            "):
    items = "".join(
        f'{indent}    <item android:offset="{o:g}" android:color="{argb(c)}" />\n' for o, c in stops
    )
    return (
        f'{indent}<gradient android:type="linear" android:startX="{x0:g}" android:startY="{y0:g}"'
        f' android:endX="{x1:g}" android:endY="{y1:g}">\n{items}{indent}</gradient>\n'
    )


def background_xml():
    return (
        VEC_HEAD
        + '    <path android:pathData="M0,0 H108 V108 H0 Z">\n'
        + '        <aapt:attr name="android:fillColor">\n'
        + gradient(0, 0, 108, 108, [(0, BG_TOP), (1, BG_BOTTOM)])
        + "        </aapt:attr>\n    </path>\n</vector>\n"
    )


def foreground_xml(mono=False):
    """Full-colour foreground, or (mono) a single-colour version for themed icons and notifications."""
    white = "#FFFFFFFF"
    out = VEC_HEAD
    # Track: the unfilled part of the dial.
    out += (
        f'    <path android:pathData="{arc(START, TRACK_END)}" android:strokeColor="{white}"\n'
        f'        android:strokeAlpha="{0.35 if mono else 0.16}" android:strokeWidth="{STROKE:g}"'
        ' android:strokeLineCap="round" />\n'
    )
    # Filled part of the dial.
    if mono:
        out += (
            f'    <path android:pathData="{arc(START, FILL_END)}" android:strokeColor="{white}"\n'
            f'        android:strokeWidth="{STROKE:g}" android:strokeLineCap="round" />\n'
        )
    else:
        out += (
            f'    <path android:pathData="{arc(START, FILL_END)}" android:strokeWidth="{STROKE:g}"\n'
            '        android:strokeLineCap="round">\n'
            '        <aapt:attr name="android:strokeColor">\n'
            + gradient(*G0, *G1, WARM)
            + "        </aapt:attr>\n    </path>\n"
        )
    out += f'    <path android:pathData="{KNOB}" android:fillColor="{white}" />\n'
    out += (
        f'    <path android:pathData="{PROFILE}" android:fillColor="{white}" android:strokeColor="{white}"\n'
        f'        android:strokeWidth="{PROFILE_STROKE:g}" android:strokeLineJoin="round" />\n'
    )
    return out + "</vector>\n"


def small_icon_xml():
    """24 dp notification icon: the foreground scaled to fill it, white on transparent."""
    fg = foreground_xml(mono=True)
    # Crop to the art (about 21..87) so it isn't tiny in the status bar.
    return (
        fg.replace('android:width="108dp"', 'android:width="24dp"')
        .replace('android:height="108dp"', 'android:height="24dp"')
        .replace('android:viewportWidth="108"', 'android:viewportWidth="66"')
        .replace('android:viewportHeight="108"', 'android:viewportHeight="66"')
        .replace("    android:viewportHeight=\"66\">\n", "    android:viewportHeight=\"66\">\n    <group android:translateX=\"-21\" android:translateY=\"-21\">\n", 1)
        .replace("</vector>", "    </group>\n</vector>")
    )


ADAPTIVE = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tools/icon/make_icon.py. -->\n"
    '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
    '    <background android:drawable="@drawable/ic_launcher_background" />\n'
    '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
    '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
    "</adaptive-icon>\n"
)


# ------------------------------------------------------------------ SVG (same geometry)

def svg(size=108, rounded=True):
    stops = "".join(f'<stop offset="{o:g}" stop-color="{c}"/>' for o, c in WARM)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="15 15 78 78" width="{size}" height="{size}">'
        "<defs>"
        f'<linearGradient id="bg" x1="0" y1="0" x2="108" y2="108" gradientUnits="userSpaceOnUse">'
        f'<stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/></linearGradient>'
        f'<linearGradient id="warm" x1="{G0[0]:g}" y1="{G0[1]:g}" x2="{G1[0]:g}" y2="{G1[1]:g}" '
        f'gradientUnits="userSpaceOnUse">{stops}</linearGradient>'
        f'<clipPath id="shape"><rect x="15" y="15" width="78" height="78" rx="{18 if rounded else 0}"/></clipPath>'
        "</defs>"
        '<g clip-path="url(#shape)">'
        '<rect width="108" height="108" fill="url(#bg)"/>'
        f'<path d="{arc(START, TRACK_END)}" fill="none" stroke="#FFFFFF" stroke-opacity="0.16" '
        f'stroke-width="{STROKE:g}" stroke-linecap="round"/>'
        f'<path d="{arc(START, FILL_END)}" fill="none" stroke="url(#warm)" stroke-width="{STROKE:g}" '
        'stroke-linecap="round"/>'
        f'<path d="{KNOB}" fill="#FFFFFF"/>'
        f'<path d="{PROFILE}" fill="#FFFFFF" stroke="#FFFFFF" stroke-width="{PROFILE_STROKE:g}" '
        'stroke-linejoin="round"/>'
        "</g></svg>\n"
    )


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", path)


if __name__ == "__main__":
    for module in ("MerachRide/app", "MerachRide/wear"):
        res = f"{module}/src/main/res"
        write(f"{res}/drawable/ic_launcher_background.xml", background_xml())
        write(f"{res}/drawable/ic_launcher_foreground.xml", foreground_xml())
        write(f"{res}/drawable/ic_launcher_monochrome.xml", foreground_xml(mono=True))
        write(f"{res}/mipmap-anydpi-v26/ic_launcher.xml", ADAPTIVE)
        write(f"{res}/mipmap-anydpi-v26/ic_launcher_round.xml", ADAPTIVE)
    write("MerachRide/app/src/main/res/drawable/ic_stat_merachride.xml", small_icon_xml())
    write("branding/logo.svg", svg(512))
